"""Final verification against the REAL regenerated dump (no synthetic intermediate).

1. Unity's own label_membership (from the regenerated catalog_dump_shipped.json) is compared against
   the independent offline reader of catalog.bin -- two completely different code paths.
2. Every plan file is regenerated by the real planner from the real dump.
3. The plan invariants are re-checked on the result.
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(REPO, "tools", "unity-rebuild", "out", "unity")
DUMP = os.path.join(OUT, "catalog_dump_shipped.json")
TSV = os.path.join(OUT, "catalog_dump_shipped_label_membership.tsv")
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(REPO, "tools", "unity-rebuild"))

from parse_catalog_membership import Catalog, CATALOG  # noqa: E402

# ---- 1. Unity dump vs the offline reader ------------------------------------------------
dump = json.load(open(DUMP, encoding="utf-8"))
cat = Catalog(CATALOG)
_header, keys = cat.keys()
offline = {}          # key -> number of location edges
for k, offs in keys:
    if len(offs) > 1:
        offline[k] = len(offs)

unity = {r["key"]: r["location_count"] for r in dump["label_membership"]}
print("label-like keys   : unity=%d offline=%d  same set=%s" % (
    len(unity), len(offline), set(unity) == set(offline)))
print("membership edges  : unity=%d offline=%d  equal=%s" % (
    sum(unity.values()), sum(offline.values()), unity == offline))
print("per-key truncation: unity=%d offline=0 (offline never truncates)" % (
    sum(1 for r in dump["label_membership"] if r["locations_truncated"])))
print("keys_with_complete_locations=%s (57212 keys - 2 truncated = 57210 expected)"
      % dump["keys_with_complete_locations"])

# the TSV side artifact must carry exactly one line per edge (plus its comment header)
tsv_lines = [l for l in open(TSV, encoding="utf-8").read().splitlines() if not l.startswith("#")]
tsv_by_key = collections.Counter(l.split("\t", 1)[0] for l in tsv_lines)
print("TSV artifact      : lines=%d (edges=%d) per-key equal to the JSON section=%s  bytes=%d"
      % (len(tsv_lines), sum(unity.values()), dict(tsv_by_key) == unity, os.path.getsize(TSV)))

# exact membership equality for the umbrella key that started all this
nani_json = next(r for r in dump["label_membership"] if r["key"] == "Naninovel")
placeholder = "{UnityEngine.AddressableAssets.Addressables.RuntimePath}"
runtime_path = dump.get("runtime_path_used") or ""
raw_to_dump = {}
for l in dump["locations"]:
    raw_to_dump[l["internal_id"]] = l["internal_id"]
    if l.get("shipped_internal_id"):
        raw_to_dump[l["shipped_internal_id"]] = l["internal_id"]
offline_nani = [raw_to_dump.get(cat.location(o)[1]) or cat.location(o)[1].replace(placeholder, runtime_path)
                for o in dict(keys)["Naninovel"]]
print("Naninovel         : unity=%d offline=%d identical-multiset=%s"
      % (len(nani_json["locations"]), len(offline_nani),
         collections.Counter(nani_json["locations"]) == collections.Counter(offline_nani)))

# ---- 2. regenerate every plan from the real dump ----------------------------------------
import a13f_plan_addressables as planner  # noqa: E402
planner.SHIPPED_DUMP = DUMP
print()
for group in ("all", "core", "prefabs"):
    sys.argv = ["a13f_plan_addressables.py", "--group", group]
    rc = planner.main()
    doc = json.load(open(os.path.join(OUT, "addressables_plan_%s.json" % group), encoding="utf-8"))
    print(">>> %-8s exit=%d entries=%-6d with_labels=%-6d Naninovel=%-6s labels=%-3d complete=%s "
          "keys_from_list=%s keys_from_membership=%s warnings=%d"
          % (group, rc, doc["entry_count"], doc["entries_with_labels"],
             doc["labels_used"].get("Naninovel"), doc["labels_used_distinct"], doc["membership_complete"],
             doc["shipped_keys_from_complete_lists"], doc["shipped_keys_from_label_membership"],
             len(doc["membership_warnings"])))
    print()

# ---- 3. invariants on the full plan -----------------------------------------------------
doc = json.load(open(os.path.join(OUT, "addressables_plan_all.json"), encoding="utf-8"))
entries = doc["entries"]
nani = set(nani_json["locations"])
labelled = [e for e in entries if "Naninovel" in e["labels"]]
paths = {e["container_path"] for e in labelled}
pks = {l["primary_key"] for l in dump["locations"]}
labels = {l for e in entries for l in e["labels"]}
print("plan entries with the Naninovel label :", len(labelled))
print("distinct container paths covered      :", len(paths), "of", len(nani), "shipped records /",
      len(set(nani)), "distinct paths")
print("shipped umbrella paths with no entry  :", len(set(nani) - paths))
print("entries whose address is also a label :", sum(1 for e in entries if e["address"] in e["labels"]))
print("labels that are some location's address:", len(labels & pks))
print("labels_used                           :", {k: doc["labels_used"][k] for k in
      ("Naninovel", "Audio-Sfx", "Scripts-System", "Scripts-Common", "Audio-Ambient_001")})
