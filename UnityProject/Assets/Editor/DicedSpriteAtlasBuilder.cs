using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Newtonsoft.Json.Linq;
using SpriteDicing;
using UnityEditor;
using UnityEngine;

namespace Manosaba.EditorTools
{
    /// <summary>
    /// Creates the <see cref="DicedSpriteAtlas"/> assets the game loads for its 18 diced-sprite characters (Yuki, Warden,
    /// Jailer*, Creature*): Naninovel's DicedSprite actors resolve `Characters/{id}` to one atlas asset and pick a sprite
    /// by its name (DicedSpriteAtlas.GetSprite).
    ///
    /// The shipped atlas is a ScriptableObject { sprites, textures } whose sprites are sub-assets generated by SpriteDicing
    /// (dice geometry over one packed texture).  The extraction exported every sprite already composed, as a PNG named after
    /// the sprite (`Warden.sprites/7.png`, imported as a single Sprite named "7") and the packed texture as `Warden.png`;
    /// the atlas dump (`res/.../Warden.asset.json`) lists the sprites / textures by path id and the import ledger maps each
    /// path id to that PNG.  This builder recreates the atlas asset with the same two lists over those imported assets.  The
    /// sprites are plain quads instead of dice meshes; DicedSpriteActor only reads Sprite.vertices / uv / triangles / texture /
    /// pivot / pixelsPerUnit, so the rendered result is the same picture.
    ///
    /// Inputs : tools/unity-rebuild/out/unity/a13_import_ledger.csv, res/Assets/#WitchTrials/Textures/Naninovel/Characters/DicedSpriteAtlases/*.asset.json
    /// Outputs: Assets/GameContent/#WitchTrials/Textures/Naninovel/Characters/DicedSpriteAtlases/*.asset (one per atlas),
    ///          tools/unity-rebuild/out/unity/diced_atlas_plan.json (the container -> asset list a13f_plan_addressables.py reads),
    ///          tools/unity-rebuild/out/unity/diced_atlas_result.json
    /// Run    : Unity -batchmode -quit -projectPath UnityProject -executeMethod Manosaba.EditorTools.DicedSpriteAtlasBuilder.Run
    /// </summary>
    public static class DicedSpriteAtlasBuilder
    {
        private const string ContainerPrefix = "Assets/#WitchTrials/Textures/Naninovel/Characters/DicedSpriteAtlases/";
        private const string TargetPrefix = "Assets/GameContent/#WitchTrials/Textures/Naninovel/Characters/DicedSpriteAtlases/";

        [MenuItem("Manosaba/Build Diced Sprite Atlases")]
        public static void Run()
        {
            string repo = Path.GetFullPath(Path.Combine(Application.dataPath, "../.."));
            string outDir = Path.Combine(repo, "tools", "unity-rebuild", "out", "unity");
            var report = new JObject { ["generated"] = DateTime.UtcNow.ToString("o") };
            int failures = 0;
            try
            {
                var rows = ReadCsv(Path.Combine(outDir, "a13_import_ledger.csv"));
                // container -> path id -> imported project asset path (Sprite / Texture2D rows only)
                var assetsByContainer = new Dictionary<string, Dictionary<string, string>>();
                var containers = new SortedDictionary<string, string>(StringComparer.Ordinal); // container -> dump (relative to res/)
                foreach (var row in rows)
                {
                    string container = row["asset_path"];
                    if (!container.StartsWith(ContainerPrefix, StringComparison.Ordinal) || !container.EndsWith(".asset", StringComparison.Ordinal)) continue;
                    string type = row["type"];
                    if (type == "MonoBehaviour") containers[container] = row["output_file"];
                    else if ((type == "Sprite" || type == "Texture2D") && row["status"] == "IMPORTED")
                    {
                        if (!assetsByContainer.TryGetValue(container, out var map)) assetsByContainer[container] = map = new Dictionary<string, string>();
                        string target = row["target_path"].Replace('\\', '/');
                        if (target.StartsWith("UnityProject/", StringComparison.Ordinal)) target = target.Substring("UnityProject/".Length);
                        map[row["path_id"]] = target;
                    }
                }

                var results = new JArray();
                var plan = new JArray();
                foreach (var pair in containers)
                {
                    string container = pair.Key;
                    string name = Path.GetFileNameWithoutExtension(container);
                    var result = new JObject { ["atlas"] = name };
                    results.Add(result);
                    try
                    {
                        var dump = JObject.Parse(File.ReadAllText(Path.Combine(repo, "res", pair.Value.Replace('/', Path.DirectorySeparatorChar)), Encoding.UTF8));
                        assetsByContainer.TryGetValue(container, out var map);
                        var sprites = new List<Sprite>();
                        var textures = new List<Texture2D>();
                        foreach (var pptr in (JArray)dump["sprites"])
                        {
                            string id = (string)pptr["m_PathID"];
                            if (map == null || !map.TryGetValue(id, out string path)) throw new InvalidDataException("sprite path id " + id + " has no imported asset");
                            var sprite = LoadSprite(path);
                            if (!sprite) throw new InvalidDataException("not a Sprite: " + path);
                            sprites.Add(sprite);
                        }
                        foreach (var pptr in (JArray)dump["textures"])
                        {
                            string id = (string)pptr["m_PathID"];
                            if (map == null || !map.TryGetValue(id, out string path)) throw new InvalidDataException("texture path id " + id + " has no imported asset");
                            var texture = AssetDatabase.LoadAssetAtPath<Texture2D>(path);
                            if (!texture) throw new InvalidDataException("not a Texture2D: " + path);
                            textures.Add(texture);
                        }

                        string atlasPath = TargetPrefix + name + ".asset";
                        var atlas = AssetDatabase.LoadAssetAtPath<DicedSpriteAtlas>(atlasPath);
                        if (!atlas)
                        {
                            atlas = ScriptableObject.CreateInstance<DicedSpriteAtlas>();
                            atlas.name = name;
                            AssetDatabase.CreateAsset(atlas, atlasPath);
                        }
                        var serialized = new SerializedObject(atlas);
                        Fill(serialized.FindProperty("sprites"), sprites);
                        Fill(serialized.FindProperty("textures"), textures);
                        serialized.ApplyModifiedPropertiesWithoutUndo();
                        EditorUtility.SetDirty(atlas);

                        var spriteNames = new JArray();
                        foreach (var sprite in sprites) spriteNames.Add(sprite.name);
                        result["status"] = "OK";
                        result["path"] = atlasPath;
                        result["sprites"] = spriteNames;
                        result["textures"] = textures.Count;
                        plan.Add(new JObject { ["asset_path"] = container, ["target"] = "UnityProject/" + atlasPath, ["sprites"] = spriteNames });
                    }
                    catch (Exception ex)
                    {
                        failures++;
                        result["status"] = "FAIL";
                        result["error"] = ex.Message;
                    }
                }
                AssetDatabase.SaveAssets();
                AssetDatabase.Refresh();
                report["atlases"] = results;
                report["atlas_count"] = containers.Count;
                report["failures"] = failures;
                report["status"] = failures == 0 && containers.Count > 0 ? "OK" : "FAIL";
                File.WriteAllText(Path.Combine(outDir, "diced_atlas_plan.json"),
                    new JObject { ["jobs"] = plan }.ToString(), new UTF8Encoding(false));
            }
            catch (Exception ex)
            {
                failures++;
                report["status"] = "ERROR";
                report["error"] = ex.ToString();
                Debug.LogException(ex);
            }
            Directory.CreateDirectory(outDir);
            File.WriteAllText(Path.Combine(outDir, "diced_atlas_result.json"), report.ToString(), new UTF8Encoding(false));
            Debug.Log("[DicedSpriteAtlasBuilder] " + report["status"] + " failures=" + failures);
            if (Application.isBatchMode) EditorApplication.Exit(failures == 0 ? 0 : 1);
        }

        private static Sprite LoadSprite(string path)
        {
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
            if (sprite) return sprite;
            foreach (var asset in AssetDatabase.LoadAllAssetsAtPath(path))
                if (asset is Sprite sub) return sub;
            return null;
        }

        private static void Fill<T>(SerializedProperty list, List<T> items) where T : UnityEngine.Object
        {
            list.arraySize = items.Count;
            for (int i = 0; i < items.Count; i++)
                list.GetArrayElementAtIndex(i).objectReferenceValue = items[i];
        }

        /// <summary>RFC 4180 reader for the import ledger (the `reason` column contains commas inside quotes).</summary>
        private static List<Dictionary<string, string>> ReadCsv(string path)
        {
            var text = File.ReadAllText(path, Encoding.UTF8);
            if (text.Length > 0 && text[0] == '﻿') text = text.Substring(1);
            var records = new List<List<string>>();
            var record = new List<string>();
            var field = new StringBuilder();
            bool quoted = false;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (quoted)
                {
                    if (c == '"')
                    {
                        if (i + 1 < text.Length && text[i + 1] == '"') { field.Append('"'); i++; }
                        else quoted = false;
                    }
                    else field.Append(c);
                }
                else if (c == '"') quoted = true;
                else if (c == ',') { record.Add(field.ToString()); field.Clear(); }
                else if (c == '\n' || c == '\r')
                {
                    if (c == '\r' && i + 1 < text.Length && text[i + 1] == '\n') i++;
                    record.Add(field.ToString()); field.Clear();
                    if (record.Count > 1 || record[0].Length > 0) records.Add(record);
                    record = new List<string>();
                }
                else field.Append(c);
            }
            if (field.Length > 0 || record.Count > 0) { record.Add(field.ToString()); records.Add(record); }

            var header = records[0];
            var rows = new List<Dictionary<string, string>>();
            for (int r = 1; r < records.Count; r++)
            {
                var row = new Dictionary<string, string>();
                for (int c = 0; c < header.Count; c++) row[header[c]] = c < records[r].Count ? records[r][c] : "";
                rows.Add(row);
            }
            return rows;
        }
    }
}
